const COLS = 360;
const ROWS = 180;

let grid: Uint8Array | null = null;

function decode() {
  const cells = new Uint8Array(COLS * ROWS);
  let index = 0;
  let land = 0;
  for (const token of LAND_RLE.split(",")) {
    const run = parseInt(token, 36);
    if (land) cells.fill(1, index, index + run);
    index += run;
    land ^= 1;
  }
  return cells;
}

/** True when the 1° cell containing (lat, lon) is land. */
export function isLand(lat: number, lon: number) {
  grid ??= decode();
  const row = Math.min(ROWS - 1, Math.max(0, Math.floor(90 - lat)));
  const col = ((Math.floor(lon + 180) % COLS) + COLS) % COLS;
  return grid[row * COLS + col] === 1;
}
